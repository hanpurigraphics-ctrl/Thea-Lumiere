const dressGrid = document.getElementById("dressGrid");
const dressCount = document.getElementById("dressCount");
const categoryButtons = document.querySelectorAll(".category-pill");

const modal = document.getElementById("dressModal");
const modalMainImage = document.getElementById("modalMainImage");
const modalThumbs = document.getElementById("modalThumbs");
const modalCategory = document.getElementById("modalCategory");
const modalTitle = document.getElementById("modalTitle");
const modalDescription = document.getElementById("modalDescription");
const modalColor = document.getElementById("modalColor");
const modalSizes = document.getElementById("modalSizes");
const modalPrice = document.getElementById("modalPrice");
const modalContact = document.getElementById("modalContact");

function renderDresses(category = "All") {
  const filtered = category === "All"
    ? dresses
    : dresses.filter(dress => dress.category === category);

  dressCount.textContent = filtered.length;

  if (!filtered.length) {
    dressGrid.innerHTML = `
      <div class="empty-state">
        <h3>No dresses in this category yet.</h3>
        <p>Check another category or return to all dresses.</p>
      </div>
    `;
    return;
  }

  dressGrid.innerHTML = filtered.map(dress => `
    <article class="dress-card" tabindex="0" role="button"
      data-id="${dress.id}" aria-label="View ${dress.name}">
      <div class="dress-image">
        <img src="${dress.images[0]}" alt="${dress.name}" loading="lazy">
        <span class="dress-tag">${dress.tag}</span>
      </div>
      <div class="dress-info">
        <span class="dress-category">${dress.category}</span>
        <h3 class="dress-name">${dress.name}</h3>
        <div class="dress-meta">
          <span>${dress.color}</span>
          <span class="view-dress">View details →</span>
        </div>
      </div>
    </article>
  `).join("");

  document.querySelectorAll(".dress-card").forEach(card => {
    card.addEventListener("click", () => openModal(Number(card.dataset.id)));
    card.addEventListener("keydown", event => {
      if (event.key === "Enter" || event.key === " ") {
        event.preventDefault();
        openModal(Number(card.dataset.id));
      }
    });
  });
}

function openModal(id) {
  const dress = dresses.find(item => item.id === id);
  if (!dress) return;

  modalCategory.textContent = `${dress.category} · ${dress.tag}`;
  modalTitle.textContent = dress.name;
  modalDescription.textContent = dress.description;
  modalColor.textContent = dress.color;
  modalSizes.textContent = dress.sizes;
  modalPrice.textContent = dress.price;

  modalMainImage.src = dress.images[0];
  modalMainImage.alt = dress.name;

  modalThumbs.innerHTML = dress.images.map((image, index) => `
    <button class="modal-thumb ${index === 0 ? "active" : ""}" type="button"
      data-image="${image}" aria-label="View photo ${index + 1}">
      <img src="${image}" alt="${dress.name} photo ${index + 1}">
    </button>
  `).join("");

  modalThumbs.querySelectorAll(".modal-thumb").forEach(button => {
    button.addEventListener("click", () => {
      modalMainImage.src = button.dataset.image;
      modalThumbs.querySelectorAll(".modal-thumb").forEach(item => item.classList.remove("active"));
      button.classList.add("active");
    });
  });

modalContact.href = "https://www.facebook.com/profile.php?id=61589916311144";
modalContact.target = "_blank";
modalContact.rel = "noopener noreferrer";
  modal.classList.add("open");
  modal.setAttribute("aria-hidden", "false");
  document.body.classList.add("modal-open");
}

function closeModal() {
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");
  document.body.classList.remove("modal-open");
}

categoryButtons.forEach(button => {
  button.addEventListener("click", () => {
    categoryButtons.forEach(item => item.classList.remove("active"));
    button.classList.add("active");
    renderDresses(button.dataset.category);
    document.getElementById("collection").scrollIntoView({
      behavior: "smooth",
      block: "start"
    });
  });
});

document.querySelectorAll("[data-close-modal]").forEach(element => {
  element.addEventListener("click", closeModal);
});

document.addEventListener("keydown", event => {
  if (event.key === "Escape" && modal.classList.contains("open")) {
    closeModal();
  }
});

